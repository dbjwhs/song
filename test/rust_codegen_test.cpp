TEST(RustCodegenTest, StructWithOptionalField) {
    std::string code = parse_and_generate_rust(R"(
        namespace test;
        struct Point { i32 x; }
        struct Record {
            i32? count;
            string? name;
            Point? origin;
        }
    )");

    EXPECT_TRUE(has(code, "    pub count: Option<i32>,\n"));
    EXPECT_TRUE(has(code, "    pub name: Option<String>,\n"));
    EXPECT_TRUE(has(code, "    pub origin: Option<Point>,\n"));

    // On the wire: a bool, then the value when it is true.
    EXPECT_TRUE(has(code, "    match &val.count {\n"
                          "        Some(song_v) => {\n"
                          "            buf.encode_bool(true);\n"
                          "            buf.encode_i32(*song_v);\n"
                          "        }\n"
                          "        None => buf.encode_bool(false),\n"
                          "    }\n"));
    EXPECT_TRUE(has(code, "            buf.encode_string(song_v)?;\n"));
    EXPECT_TRUE(has(code, "            encode_Point(buf, song_v)?;\n"));
    EXPECT_TRUE(has(code, "        count: buf.decode_optional(song::Buffer::decode_i32)?,\n"));
    EXPECT_TRUE(has(code, "        name: buf.decode_optional(song::Buffer::decode_string)?,\n"));
    EXPECT_TRUE(has(code, "        origin: buf.decode_optional(decode_Point)?,\n"));
}

TEST(RustCodegenTest, StructWithArrays) {
    std::string code = parse_and_generate_rust(R"(
        namespace test;
        struct Point { i32 x; }
        struct Shape {
            i32[] counts;
            string[] names;
            Point[] points;
            f64[][] matrix;
        }
    )");

    EXPECT_TRUE(has(code, "    pub counts: Vec<i32>,\n"));
    EXPECT_TRUE(has(code, "    pub names: Vec<String>,\n"));
    EXPECT_TRUE(has(code, "    pub points: Vec<Point>,\n"));
    EXPECT_TRUE(has(code, "    pub matrix: Vec<Vec<f64>>,\n"));

    EXPECT_TRUE(has(code, "    buf.encode_array(&val.counts, |song_buf: &mut song::Buffer, song_v: &i32| {\n"
                          "        song_buf.encode_i32(*song_v);\n"
                          "        Ok(())\n"
                          "    })?;\n"));
    // A struct element goes through its own encode function.
    EXPECT_TRUE(has(code, "    buf.encode_array(&val.points, encode_Point)?;\n"));
    // A nested array is an array of arrays: a count, then each inner array.
    EXPECT_TRUE(has(code, "    buf.encode_array(&val.matrix, |song_buf: &mut song::Buffer, song_v: &Vec<f64>| {\n"
                          "        song_buf.encode_array(song_v, |song_buf: &mut song::Buffer, song_v: &f64| {\n"));

    EXPECT_TRUE(has(code, "        counts: buf.decode_array(song::Buffer::decode_i32)?,\n"));
    EXPECT_TRUE(has(code, "        points: buf.decode_array(decode_Point)?,\n"));
    EXPECT_TRUE(has(code, "        matrix: buf.decode_array(|song_buf: &mut song::Buffer| "
                          "song_buf.decode_array(song::Buffer::decode_f64))?,\n"));
}

