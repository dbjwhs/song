// These tests check the text the generator emits. That the text compiles
// (under #![deny(warnings)] and clippy) and works against the runtime crate
// is checked by rust/tests/generated.rs, which builds checked-in generator
// output; ctest runs that when cargo is installed.

// Helper to parse, resolve, and generate Rust code
static std::string parse_and_generate_rust(const std::string& source) {
    Parser parser(source);
    auto ast = parser.parse();

    Resolver resolver(ast);
    EXPECT_TRUE(resolver.resolve());

    RustCodeGenerator gen;
    return gen.generate_module(ast.namespaces.front());
}

static bool has(const std::string& code, const std::string& text) {
    return code.find(text) != std::string::npos;
}

