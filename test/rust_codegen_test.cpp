TEST(RustCodegenTest, ModuleHeader) {
    std::string code = parse_and_generate_rust(R"(
        namespace test;
        struct Point {
            i32 x;
            i32 y;
        }
    )");

    EXPECT_EQ(code.find("// Generated by songc - DO NOT EDIT\n"), 0u);
    EXPECT_TRUE(has(code, "// Source namespace: test\n"));
    EXPECT_TRUE(has(code, "//     mod test;\n"));
    // Names come from the IDL, so the naming lints are off for the module.
    EXPECT_TRUE(has(code, "#![allow(non_snake_case, non_camel_case_types, non_upper_case_globals, dead_code)]"));
    // Runtime items are named by path: an IDL type called Buffer or Result
    // cannot shadow them.
    EXPECT_FALSE(has(code, "\nuse "));
}

