TEST(RustCodegenTest, DispatchFunctions) {
    std::string code = parse_and_generate_rust(R"(
        namespace test;
        struct Tick { i32 n; }
        service Feed {
            latest(string symbol, Tick? after) -> Tick;
            reset() -> void;
            stream watch(i32 count) -> Tick;
            stream numbers() -> i32;
        }
    )");

    EXPECT_TRUE(has(code, "pub fn dispatch_Feed<T: Feed + ?Sized>(\n"
                          "    song_impl: &T,\n"
                          "    song_method: u16,\n"
                          "    song_request: &mut song::Buffer,\n"
                          "    song_response: &mut song::Buffer,\n"
                          ") -> song::Result<()> {\n"));
    EXPECT_TRUE(has(code, "        METHOD_Feed_latest => {\n"
                          "            let symbol = song_request.decode_string()?;\n"
                          "            let after = song_request.decode_optional(decode_Tick)?;\n"
                          "            let song_result = song_impl.latest(&symbol, after.as_ref())?;\n"
                          "            encode_Tick(song_response, &song_result)?;\n"
                          "            Ok(())\n"
                          "        }\n"));
    EXPECT_TRUE(has(code, "        METHOD_Feed_reset => {\n"
                          "            song_impl.reset()?;\n"
                          "            Ok(())\n"
                          "        }\n"));
    EXPECT_TRUE(has(code, "        _ => Err(song::Error::service(format!(\"Unknown method ID: {song_method}\"))),\n"));

    // Stream methods are in the stream dispatcher only.
    EXPECT_TRUE(has(code, "pub fn dispatch_Feed_stream<T: Feed + ?Sized>(\n"));
    EXPECT_TRUE(has(code, "        METHOD_Feed_watch => {\n"
                          "            let count = song_request.decode_i32()?;\n"
                          "            let mut song_typed = song::TypedStreamWriter::new(song_writer, encode_Tick);\n"
                          "            song_impl.watch(count, &mut song_typed)\n"
                          "        }\n"));
    EXPECT_TRUE(has(code, "            song_impl.numbers(&mut song_typed)\n"));
    EXPECT_TRUE(has(code, "\"Unknown streaming method ID: {song_method}\""));
    size_t unary = code.find("pub fn dispatch_Feed<");
    size_t stream = code.find("pub fn dispatch_Feed_stream<");
    EXPECT_EQ(code.substr(unary, stream - unary).find("METHOD_Feed_watch"), std::string::npos);
}

// register_<Service> registers both dispatchers and every method with the
// flags the C++ runtime uses to route a call.
TEST(RustCodegenTest, RegisterFunction) {
    std::string code = parse_and_generate_rust(R"(
        namespace test;
        service Feed {
            latest() -> i32;
            stream watch() -> i32;
        }
    )");

    EXPECT_TRUE(has(code, "pub fn register_Feed<T: Feed + ?Sized + 'static>(runtime: &mut song::ServiceRuntime, "
                          "song_impl: std::sync::Arc<T>) {\n"));
    EXPECT_TRUE(has(code, "    runtime.register_dispatcher(SERVICE_Feed, move |method, request, response| {\n"));
    EXPECT_TRUE(has(code, "    runtime.register_stream_dispatcher(SERVICE_Feed_STREAM, move |method, request, writer| {\n"));
    EXPECT_TRUE(has(code, "    runtime.register_method(SERVICE_Feed, METHOD_Feed_latest, "
                          "song::wire::method_flags::NONE);\n"));
    EXPECT_TRUE(has(code, "    runtime.register_method(SERVICE_Feed_STREAM, METHOD_Feed_watch, "
                          "song::wire::method_flags::STREAMING);\n"));
}

// Parameters no arm uses are named with a leading underscore, so a service
// of any shape compiles under #![deny(warnings)].
TEST(RustCodegenTest, UnusedDispatchParametersAreUnderscored) {
    std::string quiet = parse_and_generate_rust(R"(
        namespace test;
        service Quiet {
            nop() -> void;
        }
    )");
    EXPECT_TRUE(has(quiet, "    song_impl: &T,\n    song_method: u16,\n"
                           "    _song_request: &mut song::Buffer,\n    _song_response: &mut song::Buffer,\n"));

    std::string streams = parse_and_generate_rust(R"(
        namespace test;
        service OnlyStreams {
            stream ticks() -> i32;
        }
    )");
    EXPECT_TRUE(has(streams, "    _song_impl: &T,\n    song_method: u16,\n"
                             "    _song_request: &mut song::Buffer,\n    _song_response: &mut song::Buffer,\n"
                             ") -> song::Result<()> {\n"
                             "    Err(song::Error::service(format!(\"Unknown method ID: {song_method}\")))\n}"));
}

TEST(RustCodegenTest, MultipleServices) {
    std::string code = parse_and_generate_rust(R"(
        namespace test;
        service Alpha { ping() -> i32; }
        service Beta { pong() -> i32; }
    )");

    for (const char* item : {"pub struct AlphaProxy<'a>", "pub struct BetaProxy<'a>", "pub trait Alpha:",
                             "pub trait Beta:", "pub fn dispatch_Alpha<", "pub fn dispatch_Beta<",
                             "pub fn register_Alpha<", "pub fn register_Beta<"}) {
        EXPECT_TRUE(has(code, item)) << item;
    }
}

// =============================================================================
// What the Rust target refuses
// =============================================================================

static void expect_refused(const std::string& source, const std::string& reason) {
    try {
        std::string code = parse_and_generate_rust(source);
        FAIL() << "generated code where an error was expected";
    } catch (const std::runtime_error& e) {
        EXPECT_NE(std::string(e.what()).find(reason), std::string::npos) << e.what();
    }
}

TEST(RustCodegenTest, RefusesATypeNamedLikeARustPreludeType) {
    expect_refused(R"(
        namespace test;
        struct Option { i32 x; }
    )", "a type cannot be named 'Option'");
    expect_refused(R"(
        namespace test;
        enum String { a }
    )", "a type cannot be named 'String'");
}

// Remote objects are out of scope for the Rust target: a class is skipped,
// and a service that passes one is refused rather than generated wrong.
TEST(RustCodegenTest, ClassesAreNotGenerated) {
    std::string code = parse_and_generate_rust(R"(
        namespace test;
        class Window {
            string title;
            show() -> void;
        }
        service Plain {
            ping() -> i32;
        }
    )");
    EXPECT_FALSE(has(code, "Window"));
    EXPECT_TRUE(has(code, "pub trait Plain:"));

    expect_refused(R"(
        namespace test;
        class Window {
            string title;
        }
        service Desktop {
            front() -> Window;
        }
    )", "type 'Window' is not a struct or enum");
}
