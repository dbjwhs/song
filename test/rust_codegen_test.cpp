// A stream method becomes an iterator of decoded chunks over the service's
// _STREAM id, with the per-chunk timeout a parameter of the call.
TEST(RustCodegenTest, StreamMethodGeneratesIteratorProxy) {
    std::string code = parse_and_generate_rust(R"(
        namespace test;
        struct Tick {
            i32 n;
        }
        service Feed {
            latest() -> i32;
            stream watch(i32 count) -> Tick;
            stream numbers() -> i64;
        }
    )");

    EXPECT_TRUE(has(code, "    pub fn watch(&mut self, count: i32, chunk_timeout: Option<std::time::Duration>) -> "
                          "song::Result<song::TypedStream<'_, Tick>> {\n"));
    EXPECT_TRUE(has(code, "        let song_stream = self.conn.call_streaming(SERVICE_Feed_STREAM, "
                          "METHOD_Feed_watch, &song_req, chunk_timeout)?;\n"
                          "        Ok(song_stream.decoded(decode_Tick))\n"));
    EXPECT_TRUE(has(code, "        Ok(song_stream.decoded(song::Buffer::decode_i64))\n"));

    // The unary method on the same service still goes through call().
    EXPECT_TRUE(has(code, "self.conn.call(SERVICE_Feed, METHOD_Feed_latest, &song_req)?;"));
    // No timeout is written into the generated code.
    EXPECT_FALSE(has(code, "from_secs"));
    EXPECT_FALSE(has(code, "from_millis"));
}

