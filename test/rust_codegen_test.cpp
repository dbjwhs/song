// A doc comment of several lines keeps its prefix on every line (the parser
// joins the lines with '\n'; one prefix would leave the rest as bare text).
TEST(RustCodegenTest, MultiLineDocCommentStaysComment) {
    std::string code = parse_and_generate_rust(R"(
        namespace test;
        /// A point in space.
        /// Second line.
        struct Point {
            /// The x coordinate,
            /// measured from the left.
            i32 x;
        }
        /// Shades.
        /// Of grey.
        enum Shade {
            /// Dark.
            /// Very.
            black
        }
        /// Sets.
        /// Of bits.
        flags Bits {
            /// One.
            /// Bit.
            one = 1
        }
        /// Finds things.
        /// Slowly.
        service Finder {
            /// Finds one.
            /// Or fails.
            find(i32 id) -> Point;
            /// Finds many.
            /// One at a time.
            stream find_all() -> Point;
        }
    )");

    EXPECT_TRUE(has(code, "/// A point in space.\n/// Second line.\n#[derive("));
    EXPECT_TRUE(has(code, "    /// The x coordinate,\n    /// measured from the left.\n    pub x: i32,\n"));
    EXPECT_TRUE(has(code, "/// Shades.\n/// Of grey.\n#[derive("));
    EXPECT_TRUE(has(code, "    /// Dark.\n    /// Very.\n    #[default]\n    black = 0,\n"));
    EXPECT_TRUE(has(code, "/// Sets.\n/// Of bits.\n#[derive("));
    EXPECT_TRUE(has(code, "    /// One.\n    /// Bit.\n    pub const one: Bits = Bits(1);\n"));
    EXPECT_TRUE(has(code, "/// Finds things.\n/// Slowly.\npub struct FinderProxy<'a> {\n"));
    EXPECT_TRUE(has(code, "/// Finds things.\n/// Slowly.\n///\n/// The service side of Finder"));
    EXPECT_TRUE(has(code, "    /// Finds one.\n    /// Or fails.\n    pub fn find("));
    EXPECT_TRUE(has(code, "    /// Finds one.\n    /// Or fails.\n    fn find("));
    EXPECT_TRUE(has(code, "    /// Finds many.\n    /// One at a time.\n    ///\n    /// Streams: yields"));
    EXPECT_TRUE(has(code, "    /// Finds many.\n    /// One at a time.\n    fn find_all("));

    // No line of any doc comment is left without its prefix.
    for (const char* line : {"Second line.", "measured from the left.", "Of grey.", "Very.", "Of bits.",
                             "Bit.", "Slowly.", "Or fails.", "One at a time."}) {
        size_t pos = 0;
        while ((pos = code.find(line, pos)) != std::string::npos) {
            size_t start = code.rfind('\n', pos) + 1;
            std::string before = code.substr(start, pos - start);
            EXPECT_EQ(before.find_first_not_of(' '), before.find("/// ")) << "bare doc line: " << line;
            pos += 1;
        }
    }
}

