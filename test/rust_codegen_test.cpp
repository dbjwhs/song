// An enum travels as an i32, and a value that is no item is refused on
// decode (a Rust enum cannot hold one).
TEST(RustCodegenTest, EnumCodecs) {
    std::string code = parse_and_generate_rust(R"(
        namespace test;
        enum Color { Red, Green }
        struct Pixel {
            Color color;
            Color? tint;
            Color[] history;
        }
    )");

    EXPECT_TRUE(has(code, "pub fn encode_Color(buf: &mut song::Buffer, val: Color) {\n"
                          "    buf.encode_i32(val as i32);\n"
                          "}"));
    EXPECT_TRUE(has(code, "pub fn decode_Color(buf: &mut song::Buffer) -> song::Result<Color> {\n"
                          "    let value = buf.decode_i32()?;\n"
                          "    Color::from_i32(value).ok_or_else(|| "
                          "song::Error::decode(format!(\"unknown Color value: {value}\")))\n"
                          "}"));

    // As a field, an optional and an array element.
    EXPECT_TRUE(has(code, "    encode_Color(buf, val.color);\n"));
    EXPECT_TRUE(has(code, "            encode_Color(buf, *song_v);\n"));
    EXPECT_TRUE(has(code, "    buf.encode_array(&val.history, |song_buf: &mut song::Buffer, song_v: &Color| {\n"
                          "        encode_Color(song_buf, *song_v);\n"));
    EXPECT_TRUE(has(code, "        color: decode_Color(buf)?,\n"));
    EXPECT_TRUE(has(code, "        tint: buf.decode_optional(decode_Color)?,\n"));
    EXPECT_TRUE(has(code, "        history: buf.decode_array(decode_Color)?,\n"));
}

