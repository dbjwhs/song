"""
Writes wire_vectors.txt: named byte vectors of the Song wire format.

The bytes are computed here with struct, hmac and hashlib only, not with any
Song runtime, so the file is an independent statement of the format. The
C++, Python and Rust tests each build the same values with their own runtime
and compare byte for byte:

    test/golden_test.cpp           (C++)
    python/tests/test_golden.py    (Python, the vectors it has encoders for)
    rust/tests/golden.rs           (Rust)

The vectors are little-endian. The C++ and Rust runtimes write native byte
order, so their tests skip on a big-endian host.

    python3 test/golden/generate.py > test/golden/wire_vectors.txt
"""

import hashlib
import hmac
import struct

MAGIC = 0x534F4E47


def string(text):
    raw = text.encode("utf-8")
    return struct.pack("<I", len(raw)) + raw


def header(msg_type, seq, size, flags=0):
    return struct.pack("<IBBHII", MAGIC, flags, msg_type, 0, size, seq)


def message(msg_type, seq, payload):
    return header(msg_type, seq, len(payload)) + payload


def init_payload(first, current, caps, methods):
    out = struct.pack("<IHHII", MAGIC, first, current, caps, len(methods))
    for service, method, flags in methods:
        out += struct.pack("<HHHH", service, method, flags, 0)
    return out


def tagged(msg, key):
    size = struct.unpack_from("<I", msg, 8)[0]
    tag = hmac.new(key, msg, hashlib.sha256).digest()[:8]
    return msg[:8] + struct.pack("<I", size + 8) + msg[12:] + tag


HMAC_KEY = b"song-golden-vector-key"
CALL = message(0x02, 7, struct.pack("<HHii", 1, 2, 5, 9))

VECTORS = [
    ("# primitives", None),
    ("bool_true", b"\x01"),
    ("bool_false", b"\x00"),
    ("i8_minus_2", struct.pack("<b", -2)),
    ("i16_minus_2", struct.pack("<h", -2)),
    ("i32_0x12345678", struct.pack("<i", 0x12345678)),
    ("i64_minus_2", struct.pack("<q", -2)),
    ("u8_0xab", struct.pack("<B", 0xAB)),
    ("u16_0xbeef", struct.pack("<H", 0xBEEF)),
    ("u32_0xdeadbeef", struct.pack("<I", 0xDEADBEEF)),
    ("u64_0x0102030405060708", struct.pack("<Q", 0x0102030405060708)),
    ("f32_1_5", struct.pack("<f", 1.5)),
    ("f64_minus_2_25", struct.pack("<d", -2.25)),
    ("# strings and bytes: u32 length, then the bytes", None),
    ("string_hello", string("hello, song")),
    ("string_empty", string("")),
    ("string_utf8", string("héllo ♫")),
    ("bytes_00_ff_10", struct.pack("<I", 3) + b"\x00\xff\x10"),
    ("# arrays: u32 count, then the elements", None),
    ("array_i32", struct.pack("<Iiii", 3, 1, -1, 65536)),
    ("array_string", struct.pack("<I", 2) + string("a") + string("bc")),
    ("array_nested_i32", struct.pack("<I", 3) + struct.pack("<Iii", 2, 1, 2) + struct.pack("<I", 0)
     + struct.pack("<Ii", 1, 3)),
    ("# optionals: a bool, then the value when true", None),
    ("optional_i32_some_7", b"\x01" + struct.pack("<i", 7)),
    ("optional_none", b"\x00"),
    ("# messages: 16-byte header, then the payload", None),
    ("header_call_seq7_size4", header(0x02, 7, 4)),
    ("msg_init", message(0x01, 0, init_payload(0x0100, 0x0101, 0x41, [(1, 1, 0), (2, 3, 2)]))),
    ("msg_init_ack", message(0x0D, 0, init_payload(0x0100, 0x0101, 0x40, []))),
    ("msg_call", CALL),
    ("msg_result", message(0x03, 7, struct.pack("<i", 14))),
    ("msg_error", message(0x04, 7, struct.pack("<H", 3) + string("boom"))),
    ("msg_stream", message(0x05, 9, struct.pack("<i", 1))),
    ("msg_stream_end", message(0x06, 9, b"")),
    ("msg_shutdown", message(0x08, 0, b"")),
    ("# HMAC transport: payload_size grows by 8, the tag is the first 8 bytes", None),
    ("# of HMAC-SHA256 over the untagged message, appended to the payload", None),
    ("hmac_key", HMAC_KEY),
    ("msg_call_tagged", tagged(CALL, HMAC_KEY)),
    ("msg_stream_end_tagged", tagged(message(0x06, 9, b""), HMAC_KEY)),
]


def main():
    print("# MIT License")
    print("# Copyright (c) 2026 dbjwhs")
    print("#")
    print("# Song wire format golden vectors: name = hex bytes (little-endian host).")
    print("# Generated by test/golden/generate.py; do not edit by hand.")
    in_comment = False
    for name, value in VECTORS:
        if value is None:
            if not in_comment:
                print()
            print(name)
        else:
            print(f"{name} = {value.hex()}")
        in_comment = value is None


if __name__ == "__main__":
    main()
