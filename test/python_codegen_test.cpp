using namespace song;
using namespace song::compiler;

// Helper to parse, resolve, and generate Python code
static std::string parse_and_generate_python(const std::string& source) {
    Parser parser(source);
    auto ast = parser.parse();

    Resolver resolver(ast);
    EXPECT_TRUE(resolver.resolve());

    PythonCodeGenerator gen;
    return gen.generate_module(ast.namespaces.front());
}

// =============================================================================
// Module Structure
// =============================================================================

TEST(PythonCodegenTest, ModuleHeader) {
    std::string code = parse_and_generate_python(R"(
        namespace test;
        struct Point {
            i32 x;
            i32 y;
        }
    )");

    // Should contain generated file header
    EXPECT_NE(code.find("# Generated by songc - DO NOT EDIT"), std::string::npos);
    // Should import dataclass
    EXPECT_NE(code.find("from dataclasses import dataclass"), std::string::npos);
    // Should import IntEnum
    EXPECT_NE(code.find("from enum import IntEnum"), std::string::npos);
    // Should import song buffer and connection
    EXPECT_NE(code.find("from song.buffer import Buffer"), std::string::npos);
    EXPECT_NE(code.find("from song.connection import ServiceConnection"), std::string::npos);
}

