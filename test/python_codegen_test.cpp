TEST(PythonCodegenTest, CompleteModule) {
    std::string code = parse_and_generate_python(R"(
        namespace calculator;

        struct DivResult {
            i32 quotient;
            i32 remainder;
        }

        enum Operation {
            Add,
            Subtract,
            Multiply,
            Divide
        }

        service Calculator {
            add(i32 a, i32 b) -> i32;
            divide(i32 a, i32 b) -> DivResult;
        }
    )");

    // Module should have correct namespace reference
    EXPECT_NE(code.find("# Source: calculator.song"), std::string::npos);

    // All components should be present
    EXPECT_NE(code.find("class DivResult:"), std::string::npos);
    EXPECT_NE(code.find("class Operation(IntEnum):"), std::string::npos);
    EXPECT_NE(code.find("class CalculatorProxy:"), std::string::npos);

    // Struct should come before service proxy (order matters for Python)
    auto struct_pos = code.find("class DivResult:");
    auto proxy_pos = code.find("class CalculatorProxy:");
    EXPECT_LT(struct_pos, proxy_pos);
}

