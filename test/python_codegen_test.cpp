TEST(PythonCodegenTest, SimpleStruct) {
    std::string code = parse_and_generate_python(R"(
        namespace test;
        struct Point {
            i32 x;
            i32 y;
        }
    )");

    // Should contain dataclass definition
    EXPECT_NE(code.find("@dataclass"), std::string::npos);
    EXPECT_NE(code.find("class Point:"), std::string::npos);
    EXPECT_NE(code.find("x: int"), std::string::npos);
    EXPECT_NE(code.find("y: int"), std::string::npos);

    // Should contain encode/decode functions
    EXPECT_NE(code.find("def encode_Point(buf: Buffer, val: Point) -> None:"), std::string::npos);
    EXPECT_NE(code.find("def decode_Point(buf: Buffer) -> Point:"), std::string::npos);
}

TEST(PythonCodegenTest, StructWithAllPrimitives) {
    std::string code = parse_and_generate_python(R"(
        namespace test;
        struct AllTypes {
            bool flag;
            i8 byte_val;
            i16 short_val;
            i32 int_val;
            i64 long_val;
            u8 ubyte_val;
            u16 ushort_val;
            u32 uint_val;
            u64 ulong_val;
            f32 float_val;
            f64 double_val;
            string name;
            bytes data;
        }
    )");

    // Python type mappings
    EXPECT_NE(code.find("flag: bool"), std::string::npos);
    EXPECT_NE(code.find("byte_val: int"), std::string::npos);
    EXPECT_NE(code.find("int_val: int"), std::string::npos);
    EXPECT_NE(code.find("float_val: float"), std::string::npos);
    EXPECT_NE(code.find("double_val: float"), std::string::npos);
    EXPECT_NE(code.find("name: str"), std::string::npos);
    EXPECT_NE(code.find("data: bytes"), std::string::npos);

    // Encode calls should use correct buffer methods
    EXPECT_NE(code.find("buf.encode_bool(val.flag)"), std::string::npos);
    EXPECT_NE(code.find("buf.encode_i32(val.int_val)"), std::string::npos);
    EXPECT_NE(code.find("buf.encode_f64(val.double_val)"), std::string::npos);
    EXPECT_NE(code.find("buf.encode_string(val.name)"), std::string::npos);
    EXPECT_NE(code.find("buf.encode_bytes(val.data)"), std::string::npos);
}

